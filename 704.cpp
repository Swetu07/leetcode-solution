// 704 - Binary Search
#include <bits/stdc++.h>
using namespace std;

int main() {
    int n;

    cout << "Enter the size of array: ";
    cin >> n;

    vector<int> arr(n);

    cout << "Enter sorted array elements: ";
    for (int i = 0; i < n; i++) {
        cin >> arr[i];
    }

    int target;
    cout << "Enter target: ";
    cin >> target;

    int left = 0;
    int right = n - 1;
    int ans = -1;

    while (left <= right) {
        int mid = left + (right - left) / 2;

        if (arr[mid] == target) {
            ans = mid;
            break;
        }
        else if (arr[mid] < target) {
            left = mid + 1;
        }
        else {
            right = mid - 1;
        }
    }

    if (ans != -1) {
        cout << "Target found at index: " << ans << endl;
    }
    else {
        cout << "Target not found!" << endl;
    }

    return 0;
}
